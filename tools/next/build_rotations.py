"""Builds EquipThisNext/Data/Rotations.lua: each spec's default rotation, from Warcraft Logs.

For every player in the pulled fights (Classic Era 40-player raids, level 60: Molten Core, Blackwing
Lair, Temple of Ahn'Qiraj, Naxxramas), their damage (and healing) per ability, kept to their class's
own abilities (Forever's SkillLineAbility) plus auto attacks / Auto Shot (gear procs, Windfury Totem
and other people's buffs left out); shares of what's kept, averaged over the spec's players, and
casts a minute. Players who were active less than 70% of the fight are left out.
Also writes Tests/FixtureSpecs.lua: each spec's median primary stats (test characters only).

  python tools/next/build_rotations.py <fights.json> <wago csv folder>
"""
import csv, json, os, statistics, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", "..", "EquipThisNext"))
CLASS_ID = {"Warrior": 1, "Paladin": 2, "Hunter": 3, "Rogue": 4, "Priest": 5, "Shaman": 7, "Mage": 8, "Warlock": 9, "Druid": 11}
TREE = {"Feral": "Feral Combat", "BeastMastery": "Beast Mastery", "Guardian": "Feral Combat"}
ANCHOR = {"Melee": "auto attack", "Auto Shot": "auto shot"}
SCHOOL = {1: 1, 2: 2, 4: 4, 8: 8, 16: 16, 32: 32, 64: 64}
HEAL_TREES = {"Holy", "Restoration", "Discipline"}


def main():
    fights = json.load(open(sys.argv[1]))
    W = sys.argv[2]
    names = {r["ID"]: r["Name_lang"] for r in csv.DictReader(open(os.path.join(W, "SpellName.csv"), encoding="utf-8"))}
    class_names = collections.defaultdict(set)
    for r in csv.DictReader(open(os.path.join(W, "SkillLineAbility.csv"), encoding="utf-8")):
        m = int(r["ClassMask"] or 0)
        for cname, cid in CLASS_ID.items():
            if m & (1 << (cid - 1)) and names.get(r["Spell"]):
                class_names[cname].add(names[r["Spell"]])
    dmg = collections.defaultdict(list)    # spec -> [ {name: share} ]
    heal = collections.defaultdict(list)
    cpm = collections.defaultdict(lambda: collections.defaultdict(list))
    schools = collections.defaultdict(dict)
    stats = collections.defaultdict(lambda: collections.defaultdict(list))
    nfights = collections.defaultdict(set)
    for key, f in fights.items():
        if not f or not f.get("ms"):
            continue
        ms = f["ms"]
        casts = {e["id"]: {a["name"]: a["total"] for a in e["abilities"]} for e in f["casts"]}
        healers = {}
        for kind, table, store in (("dmg", f["dmg"], dmg), ("heal", f["heal"], heal)):
            for e in table:
                icon = e.get("icon") or ""
                if "-" not in icon or e["type"] not in CLASS_ID:
                    continue
                cls, spec = icon.split("-", 1)
                tree = TREE.get(spec, spec)
                skey = "%s:%s" % (cls.upper(), tree)
                if (e.get("active") or 0) < 0.7 * ms or not e.get("total"):
                    continue
                # healers' damage and damage dealers' healing aren't their rotation
                if (kind == "dmg") == (tree in HEAL_TREES):
                    continue
                own = {}
                for a in e["abilities"]:
                    n = ANCHOR.get(a["name"], a["name"])
                    if n in ANCHOR.values() or a["name"] in class_names[cls]:
                        own[n] = own.get(n, 0) + a["total"]
                        schools[skey][n] = SCHOOL.get(a.get("type"), a.get("type"))
                tot = sum(own.values())
                if tot <= 0:
                    continue
                store[skey].append({n: v / tot for n, v in own.items()})
                nfights[skey].add(key)
                for n in own:
                    c = casts.get(e["id"], {}).get(n if n not in ANCHOR.values() else None)
                    if c:
                        cpm[skey][n].append(c / (ms / 60000))
                for k, v in (f["stats"].get(str(e["id"])) or f["stats"].get(e["id"]) or {}).items():
                    stats[skey][k].append(v)
    L = ["-- AUTO GENERATED by tools/next/build_rotations.py: do not edit.",
         "-- Default rotations per spec: each ability's share of the spec's damage (and healing), from",
         "-- Warcraft Logs, Classic Era 40-player raids at level 60 (Molten Core, Blackwing Lair, Temple of",
         "-- Ahn'Qiraj, Naxxramas; recent public logs, Nov 2026), class abilities and auto attacks only.",
         "-- Used until /eqn measure learns a player's own. ROTATIONS[\"CLASS:Tree\"] = { players, fights,",
         "--   damage = { { name, share, school, cpm } }, healing = { { name, share, cpm } } }",
         "local _, ns = ...", "ns.ROTATIONS = {"]
    summary = []
    for skey in sorted(set(dmg) | set(heal)):
        def avg(rows):
            names_ = set(n for r in rows for n in r)
            out = {n: sum(r.get(n, 0) for r in rows) / len(rows) for n in names_}
            return sorted([(n, s) for n, s in out.items() if s >= 0.01], key=lambda x: -x[1])
        players = max(len(dmg[skey]), len(heal[skey]))
        if players < 3:
            continue
        L.append('  ["%s"] = { players = %d, fights = %d,' % (skey, players, len(nfights[skey])))
        for kind, rows in (("damage", dmg[skey]), ("healing", heal[skey])):
            if not rows:
                continue
            items = []
            for n, s in avg(rows):
                c = cpm[skey].get(n)
                items.append('{ name = "%s", share = %.4f%s%s }' % (n, s,
                    ", school = %d" % schools[skey][n] if kind == "damage" and isinstance(schools[skey].get(n), int) else "",
                    ", cpm = %.2f" % statistics.median(c) if c else ""))
            L.append("    %s = { %s }," % (kind, ", ".join(items)))
        L.append("  },")
        top = avg(dmg[skey] or heal[skey])[:4]
        summary.append("%-26s %3d players: %s" % (skey, players, ", ".join("%s %d%%" % (n, s * 100 + 0.5) for n, s in top)))
    L.append("}")
    open(os.path.join(ROOT, "Data", "Rotations.lua"), "w", newline="\n").write("\n".join(L) + "\n")
    F = ["-- AUTO GENERATED by tools/next/build_rotations.py: each spec's median primary stats in the logged",
         "-- fights (Warcraft Logs combatant info). Test characters only: never used by the addon.",
         "FIXTURE_SPECS = {"]
    for skey in sorted(stats):
        st = {k: statistics.median(v) for k, v in stats[skey].items() if k in ("Strength", "Agility", "Stamina", "Intellect", "Spirit", "Armor")}
        if st:
            F.append('  ["%s"] = { %s },' % (skey, ", ".join("%s = %d" % (k, v) for k, v in sorted(st.items()))))
    F.append("}")
    open(os.path.join(ROOT, "Tests", "FixtureSpecs.lua"), "w", newline="\n").write("\n".join(F) + "\n")
    print("\n".join(summary))


if __name__ == "__main__":
    main()
