"""Builds Procs.lua: how often each item's proc goes off, from the game client's own tables.

An item's on-equip effect (ItemXItemEffect -> ItemEffect, trigger "on equip") is a spell whose aura
holds its proc chance (SpellAuraOptions.ProcChance, % per qualifying hit or cast). Classic's
"Chance on hit" weapons mostly say 100 there: their real rate was kept on the server, so those are
left out, and Equip This! counts them as about once a minute.

Source: wago.tools (product wowf). Run:  python tools/procs/build.py [build]   (default: latest wowf)
"""
import csv
import io
import json
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "Procs.lua"))
WAGO = "https://wago.tools/db2/{}/csv?build={}"
ON_EQUIP = "1"


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "EquipThis-procs-builder"})
    with urllib.request.urlopen(req, timeout=300) as r:
        return r.read()


def latest_build():
    html = get("https://wago.tools/builds").decode("utf-8", "replace")
    m = re.search(r'"product":"wowf","version":"([\d.]+)"', html.replace("&quot;", '"'))
    if not m:
        sys.exit("could not find the latest wowf build on wago.tools; pass one as an argument")
    return m.group(1)


def table(name, build):
    return list(csv.DictReader(io.StringIO(get(WAGO.format(name, build)).decode("utf-8"))))


def main():
    build = sys.argv[1] if len(sys.argv) > 1 else latest_build()
    print("game build", build)
    effects = {r["ID"]: r for r in table("ItemEffect", build)}
    chance = {}
    for r in table("SpellAuraOptions", build):
        try:
            c = float(r["ProcChance"] or 0)
        except ValueError:
            continue
        if 0 < c < 100 and r["DifficultyID"] in ("0", ""):
            chance[r["SpellID"]] = c
    out = {}
    for r in table("ItemXItemEffect", build):
        e = effects.get(r["ItemEffectID"])
        if not e or e["TriggerType"] != ON_EQUIP:
            continue
        c = chance.get(e["SpellID"])
        if c:
            item = int(r["ItemID"])
            out[item] = max(out.get(item, 0), c)
    lines = [
        "-- AUTO GENERATED by tools/procs/build.py: do not edit.",
        "-- How often items' procs go off: % chance per qualifying hit or cast, from the game client's",
        "-- own tables (via wago.tools). Items not listed: about once a minute.",
        "local _, ns = ...",
        "ns.PROC_CHANCE = {",
        "build = %s," % ('"' + build + '"'),
    ]
    for item in sorted(out):
        v = out[item]
        lines.append("[%d]=%s," % (item, ("%g" % v)))
    lines.append("}")
    # rates the game keeps on its server, measured on Warcraft Logs (tools/procs/measured.json: procs
    # a minute of players wearing the item in recent public 40-player raid fights)
    measured = os.path.join(HERE, "measured.json")
    if os.path.exists(measured):
        with open(measured) as f:
            m = json.load(f)
        lines.append("-- Procs a minute for items whose rate the game keeps on its server, measured on Warcraft Logs")
        lines.append("-- (%s)." % m.get("source", ""))
        lines.append("ns.PROC_PPM = {")
        for item in sorted(m["ppm"], key=int):
            lines.append("[%s]=%s," % (item, "%g" % m["ppm"][item]))
        lines.append("}")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("items with a proc chance: %d -> %s" % (len(out), OUT))


if __name__ == "__main__":
    main()
